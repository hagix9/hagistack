#!/usr/bin/python3 -I
"""make-branding.py — Hagistack's dashboard images, generated from geometry.

    python3 -I make-branding.py OUTDIR [DOCSDIR]

Writes the four images Horizon shows in place of upstream's (see
../defs/python-django-horizon.toml, replace_files):

    hagistack-logo.svg         header brand (wide: mark + wordmark)
    hagistack-logo-splash.svg  login page (mark above wordmark)
    hagistack-favicon.ico      16, 32 and 48 px (PNG entries)
    hagistack-apple-touch-icon.png  180 px
    hagistack-safari-pinned-tab.svg  the mark in one colour (Safari mask icon)
    hagistack-material-brand.svg     header brand of the material theme, which
                                     includes the SVG inline in its HTML, so it
                                     has no XML declaration or comment

and, with DOCSDIR, the images that replace OpenStack's documentation theme logos
in the HTML documentation (genspec.py, DOC_BRANDING):

    hagistack-doc-logo-full.svg   header logo (the theme shows it at 135 x 35)
    hagistack-doc-logo-vert.svg   stacked logo (the theme's CSS uses it)
    hagistack-doc-logo-full.png   135 x 35, the mark (the theme's PNG fallbacks)
    hagistack-doc-logo-vert.png   59 x 54, the mark
    hagistack-doc-favicon.ico     16, 32 and 48 px

Everything is drawn from the shapes below: no font, no external file, no
script, no embedded bitmap in the SVGs. The output is byte-for-byte the same on
every run on the same zlib (test_branding.py compares the SVGs byte for byte and
the bitmaps by their decoded pixels, so another zlib build still passes), and the
images are Hagistack's own work under the MIT License.

The mark: two pillars and three layers between them, an "H" built as a stack.
Blue #3E6FE0 and amber #F0A830 read on light and on dark backgrounds.
"""
import os
import struct
import sys
import zlib

BLUE = '#3E6FE0'
AMBER = '#F0A830'
BLUE_RGB = (0x3E, 0x6F, 0xE0)
AMBER_RGB = (0xF0, 0xA8, 0x30)

# The mark on a 100 x 100 grid: (x, y, w, h, rx, colour).
MARK = [
    (6, 6, 22, 88, 5, 'blue'),
    (72, 6, 22, 88, 5, 'blue'),
    (34, 14, 32, 16, 4, 'blue'),
    (34, 42, 32, 16, 4, 'amber'),
    (34, 70, 32, 16, 4, 'blue'),
]

# The wordmark "hagistack": stroked paths on a grid with baseline y=104,
# x-height y=44, ascender y=8. (advance, [path data], [dots (cx, cy, r)])
GLYPHS = {
    'h': (58, ['M5 8V104', 'M5 70Q5 44 29 44Q53 44 53 70V104'], []),
    'a': (62, ['M57 47V104', 'M57 74Q57 44 30 44Q3 44 3 74Q3 104 30 104Q57 104 57 74'], []),
    'g': (62, ['M57 47V112Q57 136 31 136Q14 136 6 126', 'M57 74Q57 44 30 44Q3 44 3 74Q3 104 30 104Q57 104 57 74'], []),
    'i': (10, ['M5 47V104'], [(5, 22, 6.5)]),
    's': (53, ['M48 54Q42 44 27 44Q7 44 7 60Q7 73 27 74Q49 75 49 89Q49 104 27 104Q11 104 4 93'], []),
    't': (34, ['M15 18V90Q15 104 31 104', 'M2 47H32'], []),
    'c': (56, ['M53 56Q45 44 30 44Q3 44 3 74Q3 104 30 104Q45 104 53 92'], []),
    'k': (53, ['M5 8V104', 'M48 47L7 80', 'M22 68L50 104'], []),
}
WORD = 'hagistack'
GAP = 14
STROKE = 10


def word_width():
    return sum(GLYPHS[c][0] for c in WORD) + GAP * (len(WORD) - 1)


def svg_mark(x, y, scale, mono=None):
    out = []
    for (rx_, ry_, w, h, r, col) in MARK:
        out.append('<rect x="%g" y="%g" width="%g" height="%g" rx="%g" fill="%s"/>'
                   % (x + rx_ * scale, y + ry_ * scale, w * scale, h * scale, r * scale,
                      mono or (BLUE if col == 'blue' else AMBER)))
    return out


def svg_word(x, y, scale):
    out = ['<g transform="translate(%g %g) scale(%g)" fill="none" stroke="%s" stroke-width="%d" '
           'stroke-linecap="round" stroke-linejoin="round">' % (x, y, scale, BLUE, STROKE)]
    cx = 0
    for c in WORD:
        adv, paths, dots = GLYPHS[c]
        for d in paths:
            out.append('<path transform="translate(%d 0)" d="%s"/>' % (cx, d))
        for (dx, dy, r) in dots:
            out.append('<circle cx="%g" cy="%g" r="%g" fill="%s" stroke="none"/>' % (cx + dx, dy, r, BLUE))
        cx += adv + GAP
    out.append('</g>')
    return out


def svg_doc(w, h, body, inline=False):
    head = [] if inline else [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Hagistack logo. Hagistack\'s own work, MIT License; generated by make-branding.py. -->']
    # Inline (material theme): no width/height, so the theme's CSS height and the
    # viewBox decide the size, as with upstream's inline logo.
    size = '' if inline else ' width="%d" height="%d"' % (w, h)
    head += ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d"%s '
             'role="img" aria-label="Hagistack">' % (w, h, size),
             '<title>Hagistack</title>']
    return '\n'.join(head + body + ['</svg>']) + '\n'


def logo_svg(inline=False):
    # mark 104 tall (scale 1.04) left, wordmark right; glyph grid 8..141 tall.
    pad = 8
    ww = word_width()
    w = pad + 104 + 30 + ww + pad
    h = 150
    body = svg_mark(pad, (h - 104) / 2 - 4, 1.04) + svg_word(pad + 104 + 30, 0, 1)
    return svg_doc(int(w), h, body, inline)


def pinned_tab_svg():
    return svg_doc(100, 100, svg_mark(0, 0, 1, mono='#000000'))


def splash_svg():
    ww = word_width()
    w = ww + 40
    mark = 160
    h = 20 + mark + 24 + 145
    body = svg_mark((w - mark) / 2, 20, mark / 100) + svg_word(20, 20 + mark + 24 - 4, 1)
    return svg_doc(int(w), int(h), body)


# --- raster (for the favicon and the touch icon) ---------------------------

def _inside_rrect(px, py, x, y, w, h, r):
    if px < x or px > x + w or py < y or py > y + h:
        return False
    cx = min(max(px, x + r), x + w - r)
    cy = min(max(py, y + r), y + h - r)
    return (px - cx) ** 2 + (py - cy) ** 2 <= r * r


def raster(size, inset, background=None, ss=4):
    """RGBA rows of the mark, inset as a fraction of size, supersampled."""
    scale = size * (1 - 2 * inset) / 100.0
    off = size * inset
    rows = []
    for j in range(size):
        row = bytearray()
        for i in range(size):
            acc = [0.0, 0.0, 0.0, 0.0]
            for sj in range(ss):
                for si in range(ss):
                    gx = ((i + (si + 0.5) / ss) - off) / scale
                    gy = ((j + (sj + 0.5) / ss) - off) / scale
                    col = None
                    for (x, y, w, h, r, c) in MARK:
                        if _inside_rrect(gx, gy, x, y, w, h, r):
                            col = BLUE_RGB if c == 'blue' else AMBER_RGB
                            break
                    if col is None and background is not None:
                        col = background
                    if col is not None:
                        acc[0] += col[0]; acc[1] += col[1]; acc[2] += col[2]; acc[3] += 255
            n = ss * ss
            a = acc[3] / n
            if a:
                rgb = [round(acc[k] / (acc[3] / 255)) for k in range(3)]
            else:
                rgb = [0, 0, 0]
            row += bytes(rgb + [round(a)])
        rows.append(bytes(row))
    return rows


def raster_box(width, height, side, x0, y0, ss=4):
    """RGBA rows of a width x height transparent canvas with the mark drawn in the
    side x side square at (x0, y0)."""
    scale = side / 100.0
    rows = []
    for j in range(height):
        row = bytearray()
        for i in range(width):
            acc = [0.0, 0.0, 0.0, 0.0]
            for sj in range(ss):
                for si in range(ss):
                    gx = ((i + (si + 0.5) / ss) - x0) / scale
                    gy = ((j + (sj + 0.5) / ss) - y0) / scale
                    for (x, y, w, h, r, c) in MARK:
                        if _inside_rrect(gx, gy, x, y, w, h, r):
                            col = BLUE_RGB if c == 'blue' else AMBER_RGB
                            acc[0] += col[0]; acc[1] += col[1]; acc[2] += col[2]; acc[3] += 255
                            break
            a = acc[3] / (ss * ss)
            rgb = [round(acc[k] / (acc[3] / 255)) for k in range(3)] if a else [0, 0, 0]
            row += bytes(rgb + [round(a)])
        rows.append(bytes(row))
    return rows


def png(rows, size, height=None):
    def chunk(t, data):
        return struct.pack('>I', len(data)) + t + data + struct.pack('>I', zlib.crc32(t + data) & 0xffffffff)
    raw = b''.join(b'\x00' + r for r in rows)
    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size if height is None else height, 8, 6, 0, 0, 0))
            + chunk(b'tEXt', b'Software\x00Hagistack make-branding.py (MIT License)')
            + chunk(b'IDAT', zlib.compress(raw, 9))
            + chunk(b'IEND', b''))


def ico(sizes):
    images = [png(raster(s, 0.04), s) for s in sizes]
    head = struct.pack('<HHH', 0, 1, len(images))
    off = 6 + 16 * len(images)
    entries = b''
    for s, data in zip(sizes, images):
        entries += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(data), off)
        off += len(data)
    return head + entries + b''.join(images)


def doc_files():
    return {
        'hagistack-doc-logo-full.svg': logo_svg().encode(),
        'hagistack-doc-logo-vert.svg': splash_svg().encode(),
        'hagistack-doc-logo-full.png': png(raster_box(135, 35, 31, 2, 2), 135, 35),
        'hagistack-doc-logo-vert.png': png(raster_box(59, 54, 50, 4.5, 2), 59, 54),
        'hagistack-doc-favicon.ico': ico([16, 32, 48]),
    }


def main(argv):
    if len(argv) not in (2, 3):
        print(__doc__.splitlines()[2].strip())
        return 2
    out = argv[1]
    if len(argv) == 3:
        for name, data in doc_files().items():
            with open(os.path.join(argv[2], name), 'wb') as f:
                f.write(data)
    files = {
        'hagistack-logo.svg': logo_svg().encode(),
        'hagistack-logo-splash.svg': splash_svg().encode(),
        'hagistack-favicon.ico': ico([16, 32, 48]),
        'hagistack-apple-touch-icon.png': png(raster(180, 0.14, background=(255, 255, 255)), 180),
        'hagistack-safari-pinned-tab.svg': pinned_tab_svg().encode(),
        'hagistack-material-brand.svg': logo_svg(inline=True).encode(),
    }
    for name, data in files.items():
        with open(os.path.join(out, name), 'wb') as f:
            f.write(data)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
